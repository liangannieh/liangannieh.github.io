async function createShareImageBlob(data) {
  const width = 1200;
  const measureCanvas = document.createElement("canvas");
  const measureContext = measureCanvas.getContext("2d");
  const measuredHeight = Math.ceil(drawShareCardContent(measureContext, data, width, 0, true));
  const scale = 2;
  const canvas = document.createElement("canvas");
  canvas.width = width * scale;
  canvas.height = measuredHeight * scale;
  const context = canvas.getContext("2d");
  context.scale(scale, scale);
  drawShareCardContent(context, data, width, measuredHeight, false);
  return canvasToBlob(canvas);
}

async function copyResult() {
  const data = state.shareData || getShareData();
  const text = state.shareText || getShareText(data);
  let downloadableImageDataUrl = "";
  els.copyStatus.textContent = "Готовим изображение…";
  hideSharePreview();

  downloadableImageDataUrl = await withTimeout(
    state.shareImageDataUrlPromise || Promise.resolve(""),
    1200
  ).catch(() => "");

  try {
    const imageBlob = await withTimeout(
      state.shareImagePromise || createShareImageBlob(data),
      1500
    );
    if (!imageBlob) {
      throw new Error("Изображение недоступно.");
    }
    if (!downloadableImageDataUrl) {
      downloadableImageDataUrl = await withTimeout(blobToDataUrl(imageBlob), 800).catch(() => "");
    }

    if (navigator.clipboard?.write && window.ClipboardItem) {
      try {
        await withTimeout(
          navigator.clipboard.write([
            new ClipboardItem({
              "image/png": imageBlob,
              "text/plain": new Blob([text], { type: "text/plain" })
            })
          ]),
          1500
        );
        els.copyStatus.textContent = "Полное изображение результата скопировано. Вставьте его в сообщение или документ.";
        return;
      } catch {
        await withTimeout(
          navigator.clipboard.write([
            new ClipboardItem({ "image/png": imageBlob })
          ]),
          1500
        );
        els.copyStatus.textContent = "Полное изображение результата скопировано. Вставьте его в сообщение или документ.";
        return;
      }
    }
  } catch {
    // Если копирование изображения недоступно, переходим к текстовому варианту.
  }

  if (downloadableImageDataUrl && copySelectedHtml(getShareHtml(downloadableImageDataUrl, text))) {
    els.copyStatus.textContent = "Полная карточка результата скопирована. Вставьте её в сообщение или документ.";
    return;
  }

  try {
    if (!navigator.clipboard?.writeText) {
      throw new Error("Буфер обмена для текста недоступен.");
    }
    await withTimeout(navigator.clipboard.writeText(text), 1500);
    if (downloadableImageDataUrl) {
      showSharePreview(downloadableImageDataUrl, data.primary.title);
      els.copyStatus.textContent = "Полный текст результата скопирован. Изображение показано ниже — его можно сохранить или перетащить.";
      return;
    }
    els.copyStatus.textContent = "Полный текст результата скопирован. Отправка изображения в этом браузере недоступна.";
  } catch {
    if (copyPlainTextFallback(text)) {
      if (downloadableImageDataUrl) {
        showSharePreview(downloadableImageDataUrl, data.primary.title);
        els.copyStatus.textContent = "Полный текст результата скопирован. Изображение показано ниже — его можно сохранить или перетащить.";
        return;
      }
      els.copyStatus.textContent = "Полный текст результата скопирован. Отправка изображения в этом браузере недоступна.";
      return;
    }
    if (!downloadableImageDataUrl) {
      downloadableImageDataUrl = await withTimeout(
        state.shareImageDataUrlPromise || Promise.resolve(""),
        1200
      ).catch(() => "");
    }
    if (downloadableImageDataUrl) {
      showSharePreview(downloadableImageDataUrl, data.primary.title);
      els.copyStatus.textContent = "Копирование здесь заблокировано. Полное изображение результата показано ниже — его можно сохранить или перетащить.";
      return;
    }
    els.copyStatus.textContent = "Не удалось скопировать автоматически. Выделите текст результата на этой странице, чтобы поделиться им.";
  }
}

